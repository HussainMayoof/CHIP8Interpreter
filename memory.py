class Memory:
    def __init__(self) -> None:
        self.memory = bytearray(4096)

        self.memory[0x50:0xa0] = [
            0x60, 0x90, 0x90, 0x90, 0x60, #0
            0x60, 0x20, 0x20, 0x20, 0x70, #1
            0x70, 0x10, 0x70, 0x40, 0x70, #2
            0x70, 0x10, 0x70, 0x10, 0x70, #3
            0x50, 0x50, 0x70, 0x10, 0x10, #4
            0x70, 0x40, 0x70, 0x10, 0x70, #5
            0x70, 0x40, 0x70, 0x50, 0x70, #6
            0xe0, 0x10, 0x20, 0x40, 0x80, #7
            0x70, 0x50, 0x70, 0x50, 0x70, #8
            0x70, 0x50, 0x70, 0x10, 0x70, #9
            0x70, 0x50, 0x70, 0x50, 0x00, #A
            0xe0, 0xa0, 0xf0, 0x90, 0xf0, #B
            0xf0, 0x80, 0x80, 0x80, 0xf0, #C
            0xe0, 0x90, 0x90, 0x90, 0xe0, #D
            0x70, 0x50, 0x70, 0x50, 0x70, #E
            0x70, 0x40, 0x70, 0x40, 0x40  #F
        ]

    def read(self, address: int) -> int:
        return self.memory[address]

    def write(self, address: int, value: int) -> None:
        self.memory[address] = value & 0xFF
